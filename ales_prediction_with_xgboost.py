"""**Splitting Data intro Training and Testing Data**"""

X_train, X_test, Y_train, Y_test = train_test_split(X, Y, test_size=0.2, random_state=2)

print(X.shape, X_train.shape, X_test.shape)

"""**Model Training**

XGBoost Regressor
"""

regressor = XGBRegressor()

# Preprocessing: Encode categorical features and handle date column
# Using LabelEncoder for 'Category'
X_train['Category'] = encoder.fit_transform(X_train['Category'])
X_test['Category'] = encoder.transform(X_test['Category'])

# Train the model with evaluation set to track performance
eval_set = [(X_train, Y_train), (X_test, Y_test)]
regressor = XGBRegressor(objective='reg:squarederror', # Specify a regression objective
                         n_estimators=1000) # Set a reasonable number of estimators
regressor.fit(X_train, Y_train, eval_set=eval_set, verbose=False) # verbose=False to avoid printing progress for each epoch

# Retrieve evaluation results
eval_results = regressor.evals_result()

# Plot the evaluation metric over epochs
epochs = len(eval_results['validation_0']['rmse']) # Assuming 'rmse' is the default metric
x_axis = range(0, epochs)

plt.figure(figsize=(10, 6))
plt.plot(x_axis, eval_results['validation_0']['rmse'], label='Train')
plt.plot(x_axis, eval_results['validation_1']['rmse'], label='Test')
plt.legend()
plt.ylabel('RMSE')
plt.xlabel('Boosting Rounds (Epochs)')
plt.title('XGBoost Regression Performance')
plt.show()

# Make predictions on the test data
test_data_prediction = regressor.predict(X_test)
display(test_data_prediction)

